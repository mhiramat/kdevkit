#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=scripts/env.sh
source "${SCRIPT_DIR}/env.sh"

BACKEND_DIR="${WS_ROOT}/backend"
VENV_DIR="${BACKEND_DIR}/.venv"
INSTALL_DEV=1
RUN_TESTS=0

usage() {
  cat <<EOF
Usage: $(basename "$0") [OPTIONS]

Setup script for the Kconfig Dependency Auto-Resolution Python Backend.

Options:
  --no-dev      Install runtime dependencies only (skip pytest, mypy, ruff).
  --test        Run backend pytest suite after installation.
  -h, --help    Show this help message.
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    --no-dev)
      INSTALL_DEV=0
      shift
      ;;
    --test)
      RUN_TESTS=1
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "Error: Unknown option '$1'" >&2
      usage >&2
      exit 1
      ;;
  esac
done

echo "==> [1/4] Checking Python 3.10+ prerequisite"
if ! command -v python3 >/dev/null 2>&1; then
  echo "Error: python3 is not installed." >&2
  exit 1
fi

PY_VER="$(python3 -c 'import sys; print(f"{sys.version_info.major}.{sys.version_info.minor}")')"
PY_OK="$(python3 -c 'import sys; print(int(sys.version_info >= (3, 10)))')"
if [ "${PY_OK}" -ne 1 ]; then
  echo "Error: Python >= 3.10 is required (found Python ${PY_VER})." >&2
  exit 1
fi
echo "    [OK] Python ${PY_VER}"

echo "==> [2/4] Ensuring config directories & layer files exist"
mkdir -p "${BUILD_DIR}/user_injected" "${BUILD_DIR}" "${SHARED_DIR}"
if [ ! -f "${BUILD_DIR}/solver_overlay.config" ]; then
  echo "# Auto-generated by kconfig-server (solver_overlay.config)" > "${BUILD_DIR}/solver_overlay.config"
fi

echo "==> [3/4] Creating Python virtual environment at ${VENV_DIR}"
if [ ! -x "${VENV_DIR}/bin/python" ]; then
  python3 -m venv "${VENV_DIR}"
fi

echo "==> [4/4] Installing kconfig-server package into ${VENV_DIR}"
"${VENV_DIR}/bin/pip" install --upgrade pip
if [ "${INSTALL_DEV}" -eq 1 ]; then
  "${VENV_DIR}/bin/pip" install -e "${BACKEND_DIR}[dev]"
else
  "${VENV_DIR}/bin/pip" install -e "${BACKEND_DIR}"
fi

"${VENV_DIR}/bin/kconfig-server" --help >/dev/null
echo "    [OK] kconfig-server CLI entrypoint verified: ${VENV_DIR}/bin/kconfig-server"

if [ "${RUN_TESTS}" -eq 1 ]; then
  echo "==> Running backend test suite..."
  "${VENV_DIR}/bin/pytest" "${BACKEND_DIR}/tests" -v
fi

echo "==> Kconfig backend setup complete!"
