import * as fs from 'node:fs';
import * as path from 'node:path';
import { runGit, tryGit } from './gitRunner';
import { sanitizeBranchSlug } from './gitStackEngine';
import { SeriesMetadata, StagedSeriesRecord } from './types';

export interface ParsedCoverLetter {
  subject: string;
  body: string;
}

export function defaultCoverLetterTemplate(branch: string, version: number): string {
  return [
    `Subject: ${branch}: <summary>`,
    '',
    '<Describe the motivation and high-level design of this patch series.>',
    '',
    `Changes in v${version}:`,
    '- Initial version',
    '',
  ].join('\n');
}

/**
 * Parse `.kdev/series/<slug>/cover.md` into subject and body while preserving
 * raw tabs and newlines verbatim.
 */
export function parseCoverMarkdown(content: string): ParsedCoverLetter {
  const normalized = content.replace(/\r\n/g, '\n');
  const lines = normalized.split('\n');
  let subject = '';
  let bodyStart = 0;

  if (lines.length > 0 && /^Subject:\s*/i.test(lines[0])) {
    subject = lines[0].replace(/^Subject:\s*/i, '').trim();
    bodyStart = 1;
    while (bodyStart < lines.length && lines[bodyStart] === '') {
      bodyStart += 1;
    }
  }

  const body = lines.slice(bodyStart).join('\n').replace(/\n+$/, '');
  return { subject, body };
}

/**
 * Merge edited subject & body from `cover.md` into `0000-cover-letter.patch`
 * generated by `git format-patch --cover-letter`, preserving the auto-generated
 * shortlog, diffstat, `base-commit:` trailer, and raw `\t` tabs verbatim.
 */
export function mergeCoverLetterIntoPatch(
  rawCoverPatch: string,
  coverMdContent: string
): string {
  const { subject, body } = parseCoverMarkdown(coverMdContent);
  let merged = rawCoverPatch;

  if (subject) {
    merged = merged.replace(/\*\*\* SUBJECT HERE \*\*\*/, subject);
  }
  if (body) {
    merged = merged.replace(/\*\*\* BLURB HERE \*\*\*/, body);
  }

  return merged;
}

export class SeriesStore {
  constructor(private readonly stateDir: string) {}

  public getStateDir(): string {
    return this.stateDir;
  }

  public getSeriesDir(branch: string): string {
    return path.join(this.stateDir, sanitizeBranchSlug(branch));
  }

  public getMetadataPath(branch: string): string {
    return path.join(this.getSeriesDir(branch), 'series.json');
  }

  public getCoverPath(branch: string): string {
    return path.join(this.getSeriesDir(branch), 'cover.md');
  }

  public getStagingDir(branch: string): string {
    return path.join(this.getSeriesDir(branch), 'staging');
  }

  public loadOrCreateMetadata(branch: string, baseRef = 'torvalds/master'): SeriesMetadata {
    const metaPath = this.getMetadataPath(branch);
    if (fs.existsSync(metaPath)) {
      const raw = fs.readFileSync(metaPath, 'utf-8');
      const parsed = JSON.parse(raw) as SeriesMetadata;
      if (parsed.schemaVersion === 1) {
        return parsed;
      }
    }

    const meta: SeriesMetadata = {
      schemaVersion: 1,
      branch,
      version: 1,
      subjectPrefix: 'PATCH',
      baseRef,
      recipients: { to: [], cc: [] },
      inReplyTo: null,
      stagedHistory: [],
    };
    this.saveMetadata(meta);
    return meta;
  }

  public saveMetadata(meta: SeriesMetadata): void {
    const dir = this.getSeriesDir(meta.branch);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(
      this.getMetadataPath(meta.branch),
      `${JSON.stringify(meta, null, 2)}\n`,
      'utf-8'
    );
  }

  public ensureCoverLetter(branch: string, version = 1): string {
    const coverPath = this.getCoverPath(branch);
    if (!fs.existsSync(coverPath)) {
      fs.mkdirSync(path.dirname(coverPath), { recursive: true });
      fs.writeFileSync(coverPath, defaultCoverLetterTemplate(branch, version), 'utf-8');
    }
    return coverPath;
  }

  public readCoverLetter(branch: string, version = 1): string {
    const coverPath = this.ensureCoverLetter(branch, version);
    return fs.readFileSync(coverPath, 'utf-8');
  }

  public appendRangeDiffToCover(branch: string, newVersion: number, rangeDiffText: string): string {
    const coverPath = this.ensureCoverLetter(branch, newVersion);
    const existing = fs.readFileSync(coverPath, 'utf-8').replace(/\n+$/, '');
    const section = [
      existing,
      '',
      `Changes in v${newVersion}:`,
      '- <summarize changes>',
      '',
      'Range-diff:',
      rangeDiffText.trimEnd(),
      '',
    ].join('\n');
    fs.writeFileSync(coverPath, section, 'utf-8');
    return coverPath;
  }

  public async recordStagedSnapshot(
    repoDir: string,
    branch: string,
    record: Omit<StagedSeriesRecord, 'gitRef'>
  ): Promise<StagedSeriesRecord> {
    const slug = sanitizeBranchSlug(branch);
    const gitRef = `refs/kdev/staged/${slug}/v${record.version}`;
    await runGit(repoDir, ['update-ref', gitRef, record.headSha]);

    const meta = this.loadOrCreateMetadata(branch);
    const fullRecord: StagedSeriesRecord = {
      ...record,
      gitRef,
    };
    meta.stagedHistory = meta.stagedHistory.filter((r) => r.version !== record.version);
    meta.stagedHistory.push(fullRecord);
    meta.stagedHistory.sort((a, b) => a.version - b.version);
    this.saveMetadata(meta);
    return fullRecord;
  }

  public async computeRangeDiff(
    repoDir: string,
    prevBaseSha: string,
    prevHeadSha: string,
    currBaseSha: string,
    currHeadSha: string
  ): Promise<string> {
    const res = await tryGit(repoDir, [
      'range-diff',
      '--no-color',
      `${prevBaseSha}..${prevHeadSha}`,
      `${currBaseSha}..${currHeadSha}`,
    ]);
    if (res.exitCode !== 0) {
      throw new Error(res.stderr.trim() || 'git range-diff failed');
    }
    return res.stdout;
  }

  public async bumpVersion(
    repoDir: string,
    branch: string,
    currBaseSha: string,
    currHeadSha: string
  ): Promise<{ meta: SeriesMetadata; rangeDiff: string | null }> {
    const meta = this.loadOrCreateMetadata(branch);
    const prevVersion = meta.version;
    const prevSnapshot = meta.stagedHistory.find((r) => r.version === prevVersion);

    let rangeDiff: string | null = null;
    if (prevSnapshot) {
      const refCheck = await tryGit(repoDir, ['rev-parse', '--verify', prevSnapshot.gitRef]);
      const prevHead = refCheck.exitCode === 0 ? refCheck.stdout.trim() : prevSnapshot.headSha;
      if (prevHead && prevSnapshot.baseSha) {
        rangeDiff = await this.computeRangeDiff(
          repoDir,
          prevSnapshot.baseSha,
          prevHead,
          currBaseSha,
          currHeadSha
        );
      }
    }

    meta.version = prevVersion + 1;
    this.saveMetadata(meta);
    await tryGit(repoDir, ['config', `branch.${branch}.kdev-version`, String(meta.version)]);

    return { meta, rangeDiff };
  }
}
